package com.ctrlzz14.durak.event;

/**
 * Базовый класс игрового события.
 *
 * <p>События — единственный способ, которым механика сообщает о том, что
 * произошло. Механика ничего не печатает: она возвращает типизированные
 * события, а их текстовое представление строит консольный интерфейс.</p>
 *
 * <p>Каждое событие имеет порядковый номер, присваиваемый
 * {@link GameJournal} при записи. Номера монотонно возрастают, поэтому журнал
 * можно воспроизвести в исходном порядке, а в будущем — сериализовать в JSON
 * без потери информации.</p>
 */
public abstract class GameEvent {

    private long sequence = -1L;

    /**
     * Создаёт событие.
     */
    protected GameEvent() {
        // порядковый номер присваивается журналом
    }

    /**
     * Возвращает порядковый номер события в журнале.
     *
     * @return номер события; {@code -1}, если событие ещё не записано в журнал
     */
    public final long sequence() {
        return sequence;
    }

    /**
     * Возвращает тип события.
     *
     * @return тип события
     */
    public abstract EventType type();

    /**
     * Присваивает событию порядковый номер.
     *
     * <p>Метод доступен только внутри пакета событий: нумерацией занимается
     * {@link GameJournal}, а не код, создающий событие.</p>
     *
     * @param sequence порядковый номер события
     */
    final void assignSequence(long sequence) {
        this.sequence = sequence;
    }
}

package com.ctrlzz14.durak.event;

/**
 * Тип игрового события.
 *
 * <p>Тип события позволяет журналу отбирать события по категориям, а
 * консольному интерфейсу — выбирать способ форматирования. Набор типов
 * закрыт и соответствует полному перечню событий, фиксируемых в партии.</p>
 */
public enum EventType {

    /** Партия начата: зафиксированы зерно, правила и состав игроков. */
    GAME_STARTED,
    /** Определён козырь. */
    TRUMP_CHOSEN,
    /** Карты розданы игрокам. */
    CARDS_DEALT,
    /** Атакующий выложил карты на стол. */
    ATTACK,
    /** Защищающийся отбился картой. */
    DEFEND,
    /** Защищающийся перевёл атаку на следующего игрока. */
    TRANSFER,
    /** Защищающийся взял карты со стола. */
    TAKE,
    /** Игрок добрал карты из колоды. */
    REFILL,
    /** Раунд завершён. */
    ROUND_ENDED,
    /** Партия завершена, зафиксирован результат. */
    GAME_ENDED
}

package com.ctrlzz14.durak.move;

/**
 * Тип хода.
 *
 * <p>Ход — это единица общения между интерфейсом (или ботом) и механикой.
 * Механика принимает ход, проверяет его допустимость и применяет к состоянию
 * партии.</p>
 */
public enum MoveType {

    /** Атакующий выкладывает одну или несколько карт на стол. */
    ATTACK,

    /** Защищающийся отбивает выложенную карту. */
    DEFEND,

    /** Защищающийся переводит атаку на следующего игрока. */
    TRANSFER,

    /** Защищающийся берёт карты со стола. */
    TAKE,

    /** Атакующий завершает атаку и раунд. */
    END_ATTACK
}

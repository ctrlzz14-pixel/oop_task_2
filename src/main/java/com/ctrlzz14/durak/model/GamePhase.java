package com.ctrlzz14.durak.model;

/**
 * Фаза партии.
 *
 * <p>Фаза определяет, кто и какие действия может совершать в текущий момент.
 * Механика не переходит в фазу {@link #ROUND_END} наружу: окончание раунда
 * обрабатывается движком атомарно, поэтому игрок наблюдает либо
 * {@link #ATTACK}, либо {@link #DEFENSE}, либо {@link #GAME_OVER}.</p>
 */
public enum GamePhase {

    /** Партия ещё не начата: идёт подготовка и раздача. */
    SETUP,

    /** Ходит атакующий: выкладывает карты либо завершает атаку. */
    ATTACK,

    /** Ходит защищающийся: отбивает карту либо берёт карты со стола. */
    DEFENSE,

    /** Раунд завершён, идёт добор и проверка условий окончания партии. */
    ROUND_END,

    /** Партия завершена, результат известен. */
    GAME_OVER
}

package com.ctrlzz14.durak.model;

/**
 * Режим козыря.
 *
 * <p>Козырная масть всегда определяется нижней картой колоды и известна всем
 * игрокам. Различаются режимы тем, открыта ли сама козырная карта и допускается
 * ли перевод атаки козырем.</p>
 */
public enum TrumpMode {

    /**
     * Открытый козырь: нижняя карта колоды открывается сразу после тасовки,
     * её масть становится козырной, а сама карта остаётся в колоде и
     * разыгрывается как обычная.
     */
    OPEN,

    /**
     * Закрытый козырь: нижняя карта колоды остаётся скрытой, игроки знают
     * только козырную масть. Перевод атаки козырем в этом режиме запрещён.
     */
    CLOSED
}

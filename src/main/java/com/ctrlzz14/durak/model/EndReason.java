package com.ctrlzz14.durak.model;

/**
 * Причина завершения партии.
 */
public enum EndReason {

    /**
     * У одного или нескольких игроков закончились карты: они вышли из партии
     * и считаются победителями.
     */
    PLAYER_FINISHED,

    /**
     * Колода опустела и последний раунд не дал продвижения (карты не ушли в
     * отбой): партия остановлена, побеждают игроки с наименьшим числом карт.
     */
    STALEMATE
}
